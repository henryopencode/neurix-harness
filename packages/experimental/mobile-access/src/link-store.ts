/** Private, restart-stable phone connection credentials. @module */
import { randomBytes, timingSafeEqual } from 'node:crypto'
import { credentialKey, type CredentialProvider } from '@deepseek-ai/dsh-credentials'
import { z } from 'zod'

const key = credentialKey('mobile-access', 'link')
const linkSchema = z.object({ version: z.literal(1), token: z.string().regex(/^[A-Za-z0-9_-]{43}$/), enabled: z.boolean() })
type Link = z.infer<typeof linkSchema>

/** Connection writes publish only after the credential provider commits them. */
export class LinkStore {
  private value: Link | undefined

  constructor(private readonly credentials: CredentialProvider) {}

  /** Load the connection credential and remove this plugin's retired account record. */
  async load(): Promise<void> {
    const record = await this.credentials.readRecord(key)
    if (record !== undefined) {
      if (record.kind !== 'grant') throw new Error('Unsupported phone connection credential')
      this.value = linkSchema.parse(record.payload)
    }
    await this.credentials.deleteRecord(credentialKey('neurix-account', 'owner'))
  }

  /** Whether the owner explicitly enabled or disabled access; absent before first use. */
  get enabled(): boolean | undefined { return this.value?.enabled }

  /** Current private secret; callers must never log it or return it to a phone. */
  get token(): string | undefined { return this.value?.token }

  /**
   * Create an independent 256-bit link credential.
   * @returns URL-safe secret for a candidate connection link.
   */
  generate(): string { return randomBytes(32).toString('base64url') }

  /**
   * Commit a connection credential; failure retains the previously published value.
   * @param token - candidate secret generated by this store.
   * @param enabled - whether startup should restore internet access.
   */
  async save(token: string, enabled: boolean): Promise<void> {
    const value = linkSchema.parse({ version: 1, token, enabled })
    await this.credentials.modifyRecord(key, () => Promise.resolve({ kind: 'grant', payload: value }))
    this.value = value
  }

  /**
   * Check a submitted link credential without exposing its value.
   * @param token - untrusted secret received in the HTTPS request body.
   * @returns whether access is enabled and the credential matches.
   */
  accepts(token: string): boolean {
    return this.value?.enabled === true && /^[A-Za-z0-9_-]{43}$/.test(token)
      && timingSafeEqual(Buffer.from(token), Buffer.from(this.value.token))
  }
}
